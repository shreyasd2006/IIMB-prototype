"""Turns research/i18n/strings.json into numbered translation batches, leaving out what stays in English
(personal names, paper titles and citations, emails, URLs, codes, crawl-query noise).
  python tools/i18n_batches.py split   -> research/i18n/todo/b###.json  ({"id": "English"}), research/i18n/index.json
  python tools/i18n_batches.py build   -> data/i18n-hi.js from research/i18n/done/b###.json ({"id": "हिन्दी"})
"""
import json, os, re, sys, glob, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "research", "i18n")
NUM = re.compile(r"\d[\d,.]*\d|\d")


def keep_english():
    """Strings that are names or bibliographic: read straight from the data."""
    js = r"""
global.window = global; global.IIMB = {}; const fs = require('fs');
for (const f of fs.readdirSync('data')) { if (f.startsWith('i18n')) continue; try { eval(fs.readFileSync('data/' + f, 'utf8')); } catch (e) {} }
const out = new Set(); const add = (s) => { if (typeof s === 'string' && s.trim()) out.add(s.replace(/\s+/g, ' ').trim()); };
const walk = (o, k0) => { if (Array.isArray(o)) o.forEach((x) => walk(x, k0)); else if (o && typeof o === 'object') for (const [k, v] of Object.entries(o)) {
  if (typeof v === 'string') { if (['name', 'authors', 'by', 'who', 'chair', 'email', 'phone', 'credit', 'abbr', 'id', 'url', 'u', 'src', 'source'].includes(k)) add(v);
    if (k === 'title' && (k0 === 'pubs' || k0 === 'papers' || k0 === 'publications' || k0 === 'outputs' || k0 === 'journal' || k0 === 'wp')) add(v); }
  else walk(v, k); } };
walk(IIMB);
for (const k of ['publications', 'papers', 'pubs']) if (IIMB[k]) JSON.stringify(IIMB[k], (kk, v) => { if (kk === 'title' || kk === 't' || kk === 'authors' || kk === 'venue' || kk === 'cite') add(v); return v; });
(IIMB.faculty || []).forEach((f) => (f.pubs || f.publications || []).forEach((p) => add(typeof p === 'string' ? p : p.t || p.title)));
console.log(JSON.stringify([...out]));
"""
    r = subprocess.run(["node", "-e", js], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    return set(json.loads(r.stdout))


def split():
    S = json.load(open(os.path.join(R, "strings.json"), encoding="utf-8"))
    keep = keep_english()
    todo = []
    for s, meta in S.items():
        if s in keep: continue
        if re.search(r"zzzz|“finance”", s): continue
        if re.fullmatch(r"[\w.+-]+@[\w.-]+|https?://\S+|www\.\S+|[A-Z0-9&/.\- ]{1,8}|[\d\W]+", s): continue
        if re.fullmatch(r"(Prof(essor)?\.?|Dr\.?|Mr\.?|Ms\.?|Mrs\.?)\s+[A-Z][\w.\- ]+", s): continue
        if re.search(r"\(\d{4}\)[,.]|\d+\(\d+\)|pp\. ?\d|Journal of .*\d|Vol\. ?\d", s): continue   # citations
        key = NUM.sub("{n}", s) if NUM.search(s) and len(s) < 160 else s
        todo.append(key)
    todo = sorted(set(todo), key=lambda x: (len(x) > 200, x.lower()))
    os.makedirs(os.path.join(R, "todo"), exist_ok=True)
    for f in glob.glob(os.path.join(R, "todo", "*.json")): os.remove(f)
    index, batch, size, n = {}, {}, 0, 0
    def flush():
        nonlocal batch, size, n
        if batch:
            json.dump(batch, open(os.path.join(R, "todo", f"b{n:03d}.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
            n += 1; batch, size = {}, 0
    for i, s in enumerate(todo):
        sid = str(i); index[sid] = s; batch[sid] = s; size += len(s)
        if size > 9000: flush()
    flush()
    json.dump(index, open(os.path.join(R, "index.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    print(len(S), "found;", len(todo), "to translate in", n, "batches;", sum(len(x) for x in todo), "chars")


def build():
    index = json.load(open(os.path.join(R, "index.json"), encoding="utf-8"))
    HI = {}
    for f in sorted(glob.glob(os.path.join(R, "done", "*.json"))):
        for sid, hi in json.load(open(f, encoding="utf-8")).items():
            if sid in index and hi: HI[index[sid]] = hi
    extra = os.path.join(R, "extra.json")   # hand-made keys: interaction messages, months, plural forms
    if os.path.exists(extra): HI.update(json.load(open(extra, encoding="utf-8")))
    rx = json.load(open(os.path.join(R, "rx.json"), encoding="utf-8")) if os.path.exists(os.path.join(R, "rx.json")) else []
    out = "/* Hindi dictionary for the language toggle. Generated by tools/i18n_batches.py build; edit research/i18n/done/*.json. */\n"
    out += "window.IIMB = window.IIMB || {};\nIIMB.HI = " + json.dumps(HI, ensure_ascii=False, indent=0) + ";\nIIMB.HI_RX = " + json.dumps(rx, ensure_ascii=False) + ";\n"
    open(os.path.join(ROOT, "data", "i18n-hi.js"), "w", encoding="utf-8", newline="\n").write(out)
    missing = [s for s in index.values() if s not in HI]
    print(len(HI), "entries;", len(missing), "untranslated")


if __name__ == "__main__":
    {"split": split, "build": build}[sys.argv[1]]()
